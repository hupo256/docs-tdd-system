#!/usr/bin/env node

import { spawnSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadConfig } from './lib/roots.mjs'

const CANARY = 'DOCS_TDD_DELIVERY_CANARY_V1'
const hookScript = join(dirname(fileURLToPath(import.meta.url)), 'rule-context-hook.mjs')

function invokeHook({ client, worktree, sessionId, eventName, target, toolUseId, ledgerDir }) {
  const payload = {
    hook_event_name: eventName,
    session_id: sessionId,
    cwd: worktree,
    ...(target ? { tool_use_id: toolUseId, tool_name: 'Write', tool_input: { file_path: target } } : {}),
  }
  const result = spawnSync(process.execPath, [hookScript, '--client', client], {
    cwd: worktree,
    env: { ...process.env, DOCS_TDD_RULE_LEDGER_DIR: ledgerDir },
    input: JSON.stringify(payload),
    encoding: 'utf8',
    stdio: ['pipe', 'pipe', 'pipe'],
  })
  if (result.status !== 0) throw new Error(result.stderr.trim() || `rule hook exited ${result.status}`)
  return JSON.parse(result.stdout).hookSpecificOutput || {}
}

export function runRuleContextProbe({ client, worktree, target = 'apps/web/src/__docs_tdd_probe__.tsx' }) {
  if (!['codex', 'claude', 'pi'].includes(client)) throw new Error('probe client must be codex, claude, or pi')
  const ledgerDir = mkdtempSync(join(tmpdir(), 'docs-tdd-rule-probe-'))
  const sessionId = `probe-${client}-${Date.now()}`
  try {
    if (client !== 'codex') invokeHook({ client, worktree, sessionId, eventName: 'SessionStart', ledgerDir })
    const eventName = client === 'pi' ? 'BeforeAgentStart' : client === 'claude' ? 'UserPromptSubmit' : 'SessionStart'
    const first = invokeHook({ client, worktree, sessionId, eventName, target: null, toolUseId: 'probe-1', ledgerDir })
    const text = first.additionalContext || ''
    const bytes = Buffer.byteLength(text)
    const { config } = loadConfig({ cwd: worktree, consumerWorktree: worktree })
    const budget = config.ruleInjection?.combinedBudgetBytes || 16 * 1024
    const firstPass = (!first.permissionDecision || first.permissionDecision === 'allow') && text.includes(CANARY) && bytes > 0 && bytes <= budget

    let pageCount = 1
    let duplicateSuppressed = false
    for (let index = 2; index <= 20; index += 1) {
      const nextEvent = client === 'codex' ? 'PreToolUse' : eventName
      const next = invokeHook({ client, worktree, sessionId, eventName: nextEvent, target: client === 'codex' ? target : null, toolUseId: `probe-${index}`, ledgerDir })
      if (!next.additionalContext) {
        duplicateSuppressed = true
        break
      }
      pageCount += 1
    }
    return {
      ok: firstPass && duplicateSuppressed,
      scope: 'hook-producer-contract',
      client,
      eventName,
      decision: first.permissionDecision || 'implicit-allow',
      canaryPresent: text.includes(CANARY),
      injectedBytes: bytes,
      combinedBudgetBytes: budget,
      deliveryPageCount: pageCount,
      duplicateSuppressed,
      hostReceipt: client === 'pi'
        ? 'before_agent_start message is generated by the installed extension contract'
        : client === 'claude'
          ? 'UserPromptSubmit additionalContext is delegated to Claude Code'
          : 'SessionStart additionalContext is delegated to Codex',
    }
  } finally {
    rmSync(ledgerDir, { recursive: true, force: true })
  }
}

function selfTest() {
  let rejected = false
  try {
    runRuleContextProbe({ client: 'cursor', worktree: '/tmp' })
  } catch (error) {
    rejected = /codex, claude, or pi/.test(error.message)
  }
  if (!rejected || CANARY.length < 10 || !readFileSync(hookScript, 'utf8').includes(CANARY)) process.exit(1)
  console.log('PASS rule-context-probe (client validation and shared delivery canary)')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  if (process.argv.includes('--self-test')) selfTest()
  else {
    const args = process.argv.slice(2)
    const clientIndex = args.indexOf('--client')
    const worktreeIndex = args.indexOf('--worktree')
    const targetIndex = args.indexOf('--target')
    const result = runRuleContextProbe({
      client: clientIndex >= 0 ? args[clientIndex + 1] : '',
      worktree: resolve(worktreeIndex >= 0 ? args[worktreeIndex + 1] : process.cwd()),
      ...(targetIndex >= 0 ? { target: args[targetIndex + 1] } : {}),
    })
    console.log(JSON.stringify(result, null, 2))
    process.exit(result.ok ? 0 : 1)
  }
}
